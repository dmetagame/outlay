import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const artifactPath = path.join(root, "out", "Outlay.sol", "Outlay.json");
const targetPath = path.join(root, "src", "lib", "outlay", "artifact.ts");
const artifact = JSON.parse(await readFile(artifactPath, "utf8"));
const bytecode = artifact.bytecode?.object;

if (!Array.isArray(artifact.abi) || typeof bytecode !== "string" || bytecode.length === 0) {
  throw new Error(`Incomplete Foundry artifact at ${artifactPath}`);
}

const contents = `// Generated by scripts/generate-artifact.mjs. Do not edit by hand.\n` +
  `export const outlayAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n` +
  `export const outlayBytecode = "0x${bytecode}" as const;\n`;

await mkdir(path.dirname(targetPath), { recursive: true });
await writeFile(targetPath, contents);
console.log(`wrote ${path.relative(root, targetPath)}`);

